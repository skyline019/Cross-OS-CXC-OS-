struct EFI_GRAPHICS_OUTPUT_PROTOCOL_MODE {
    uint32_t max_mode;
    uint32_t mode;
    void* info;
    uint64_t size_of_info;
    uint64_t frame_buffer_base;
    uint64_t frame_buffer_size;
};

struct EFI_GRAPHICS_OUTPUT_MODE_INFORMATION {
    uint32_t version;
    uint32_t horizontal_resolution;
    uint32_t vertical_resolution;
    uint32_t pixel_format;
    uint32_t pixel_information[4];
    uint32_t pixels_per_scan_line;
};

struct EFI_GRAPHICS_OUTPUT_PROTOCOL {
    void* query_mode;
    void* set_mode;
    void* blt;
    EFI_GRAPHICS_OUTPUT_PROTOCOL_MODE* mode;
};

using LocateProtocolFn = EFI_STATUS(EFIAPI*)(EFI_GUID*, void*, void**);

uint32_t pack_pixel(uint32_t argb) {
    const uint8_t a = static_cast<uint8_t>((argb >> 24) & 0xff);
    const uint8_t r = static_cast<uint8_t>((argb >> 16) & 0xff);
    const uint8_t g = static_cast<uint8_t>((argb >> 8) & 0xff);
    const uint8_t b = static_cast<uint8_t>(argb & 0xff);
    (void)a;
    if (gop.pixel_format == pixel_bgrx) {
        return (uint32_t{b} << 0) | (uint32_t{g} << 8) | (uint32_t{r} << 16);
    }
    return (uint32_t{r} << 0) | (uint32_t{g} << 8) | (uint32_t{b} << 16);
}

void put_pixel(uint32_t x, uint32_t y, uint32_t argb) {
    if (!mapped || x >= gop.width || y >= gop.height) {
        return;
    }
    auto* row = reinterpret_cast<uint32_t*>(
        fb_va + static_cast<uint64_t>(y) * gop.pixels_per_scanline * 4);
    row[x] = pack_pixel(argb);
}

