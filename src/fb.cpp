bool capture_gop(EFI_SYSTEM_TABLE* system_table) {
    gop = {};
    if (system_table == nullptr || system_table->boot_services == nullptr ||
        system_table->boot_services->locate_protocol == nullptr) {
        return false;
    }
    EFI_GUID gop_guid = {
        0x9042a9de, 0x23dc, 0x4a38,
        {0x96, 0xfb, 0x7a, 0xde, 0xd0, 0x80, 0x51, 0x6a},
    };
    auto locate = reinterpret_cast<LocateProtocolFn>(
        system_table->boot_services->locate_protocol);
    EFI_GRAPHICS_OUTPUT_PROTOCOL* proto = nullptr;
    const EFI_STATUS st =
        locate(&gop_guid, nullptr, reinterpret_cast<void**>(&proto));
    if (efi_error(st) || proto == nullptr || proto->mode == nullptr ||
        proto->mode->info == nullptr) {
        return false;
    }
    auto* mode_info = reinterpret_cast<EFI_GRAPHICS_OUTPUT_MODE_INFORMATION*>(
        proto->mode->info);
    if (mode_info->pixel_format == pixel_blt_only ||
        proto->mode->frame_buffer_base == 0 ||
        proto->mode->frame_buffer_size == 0 ||
        mode_info->horizontal_resolution == 0 ||
        mode_info->vertical_resolution == 0) {
        return false;
    }
    gop.phys_base = proto->mode->frame_buffer_base;
    gop.size = proto->mode->frame_buffer_size;
    gop.width = mode_info->horizontal_resolution;
    gop.height = mode_info->vertical_resolution;
    gop.pixels_per_scanline = mode_info->pixels_per_scan_line;
    gop.pixel_format = mode_info->pixel_format;
    if (gop.pixels_per_scanline < gop.width) {
        gop = {};
        return false;
    }
    return true;
}

bool initialize() {
    mapped = false;
    fb_va = nullptr;
    if (gop.phys_base == 0 || gop.size == 0) {
        return false;
    }
    uint64_t map_bytes = gop.size;
    if (map_bytes > max_map_bytes) {
        map_bytes = max_map_bytes;
    }
    const uint64_t page = 4096;
    const uint64_t phys_aligned = gop.phys_base & ~(page - 1);
    const uint64_t offset = gop.phys_base - phys_aligned;
    const uint64_t pages = (map_bytes + offset + page - 1) / page;
    for (uint64_t i = 0; i < pages; ++i) {
        if (!vmm::map_device_page(phys_aligned + i * page,
                                  fb_va_base + i * page)) {
            return false;
        }
    }
    fb_va = reinterpret_cast<uint8_t*>(fb_va_base + offset);
    mapped_span = pages * page;
    mapped = true;
    current_scale = 1;
    return true;
}

bool ready() {
    return mapped && fb_va != nullptr;
}

const GopInfo& info() {
    return gop;
}

void set_scale(uint32_t scale) {
    current_scale = (scale >= 2) ? 2u : 1u;
}

uint32_t scale() {
    return current_scale;
}

uint32_t glyph_w() {
    return glyph_base_w * current_scale;
}

uint32_t glyph_h() {
    return glyph_base_h * current_scale;
}

uint8_t* virt_base() {
    return fb_va;
}

uint64_t mapped_bytes() {
    return mapped_span;
}

void clear(uint32_t argb) {
    if (!ready()) {
        return;
    }
    fill_rect(0, 0, gop.width, gop.height, argb);
}

void fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t argb) {
    if (!ready()) {
        return;
    }
    const uint32_t px = pack_pixel(argb);
    for (uint32_t row = y; row < y + h && row < gop.height; ++row) {
        auto* line = reinterpret_cast<uint32_t*>(
            fb_va + static_cast<uint64_t>(row) * gop.pixels_per_scanline * 4);
        for (uint32_t col = x; col < x + w && col < gop.width; ++col) {
            line[col] = px;
        }
    }
}

void put_glyph(uint32_t col, uint32_t row, char ch, uint32_t fg, uint32_t bg) {
    if (!ready()) {
        return;
    }
    unsigned char uc = static_cast<unsigned char>(ch);
    if (uc < 0x20 || uc > 0x7e) {
        uc = static_cast<unsigned char>('?');
    }
    const uint8_t* glyph = font8x16[uc - 0x20];
    const uint32_t sc = current_scale == 0 ? 1u : current_scale;
    const uint32_t x0 = col * glyph_base_w * sc;
    const uint32_t y0 = row * glyph_base_h * sc;
    for (uint32_t gy = 0; gy < glyph_base_h; ++gy) {
        const uint8_t bits = glyph[gy];
        for (uint32_t gx = 0; gx < glyph_base_w; ++gx) {
            const bool on = (bits & (0x80u >> gx)) != 0;
            const uint32_t color = on ? fg : bg;
            for (uint32_t sy = 0; sy < sc; ++sy) {
                for (uint32_t sx = 0; sx < sc; ++sx) {
                    put_pixel(x0 + gx * sc + sx, y0 + gy * sc + sy, color);
                }
            }
        }
    }
}

void puts(uint32_t col, uint32_t row, const char* text, uint32_t fg,
          uint32_t bg) {
    if (text == nullptr) {
        return;
    }
    uint32_t c = col;
    for (size_t i = 0; text[i] != 0; ++i) {
        if (text[i] == '\n') {
            ++row;
            c = col;
            continue;
        }
        put_glyph(c, row, text[i], fg, bg);
        ++c;
    }
}

uint32_t cols() {
    const uint32_t gw = glyph_w();
    return ready() && gw != 0 ? gop.width / gw : 0;
}

uint32_t rows() {
    const uint32_t gh = glyph_h();
    return ready() && gh != 0 ? gop.height / gh : 0;
}

