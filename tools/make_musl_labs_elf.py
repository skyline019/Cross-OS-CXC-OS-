#!/usr/bin/env python3
"""Extract/embed musl labs.lo ET_REL — M119 real musl object plant."""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CANDIDATE_ARCHIVES = [
    Path("/usr/lib/x86_64-linux-musl/libc.a"),
    Path("/usr/lib/musl/lib/libc.a"),
]


def extract_labs(out: Path) -> None:
    ar = shutil.which("ar")
    if not ar:
        raise RuntimeError("ar not found")
    archive = next((p for p in CANDIDATE_ARCHIVES if p.is_file()), None)
    if archive is None:
        raise RuntimeError("musl libc.a not found")
    tmp = out.parent / "_musl_labs_extract"
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    try:
        subprocess.check_call([ar, "x", str(archive), "labs.lo"], cwd=tmp)
        src = tmp / "labs.lo"
        if not src.is_file():
            raise RuntimeError("labs.lo missing after ar x")
        out.write_bytes(src.read_bytes())
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def header_bytes(blob: bytes) -> str:
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        "/* Generated by tools/make_musl_labs_elf.py from musl libc.a labs.lo. */\n"
        "#pragma once\n"
        "static const unsigned char musl_labs_elf[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned musl_labs_elf_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--prebuilt", type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    try:
        extract_labs(args.output)
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        if args.prebuilt and args.prebuilt.is_file():
            print(
                f"make_musl_labs_elf: extract failed ({exc}); using prebuilt",
                file=sys.stderr,
            )
            args.output.write_bytes(args.prebuilt.read_bytes())
        else:
            raise
    blob = args.output.read_bytes()
    if blob[:4] != b"\x7fELF" or blob[16] != 1:
        raise SystemExit("output is not ELF64 ET_REL")
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
