#!/usr/bin/env python3
"""ET_REL: SysV add(rdi,rsi)->rax. Planted CRT subset for M106 #lib."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

# mov rax, rdi; add rax, rsi; ret
TEXT = bytes.fromhex("4889F84801F0C3")


def build() -> bytes:
    shstr = b"\x00.text\x00.shstrtab\x00.symtab\x00.strtab\x00"
    strtab = b"\x00add\x00"
    text = TEXT
    # layout: ehdr(64) + text + shstr + symtab(2*24) + strtab
    ehdr_sz = 64
    off_text = ehdr_sz
    off_shstr = off_text + len(text)
    off_sym = (off_shstr + len(shstr) + 7) & ~7
    pad_shstr = b"\x00" * (off_sym - (off_shstr + len(shstr)))
    off_str = off_sym + 48
    off_sh = (off_str + len(strtab) + 7) & ~7
    pad_str = b"\x00" * (off_sh - (off_str + len(strtab)))

    def shdr(name, typ, flags, addr, offset, size, link, info, align, entsz):
        return struct.pack(
            "<IIQQQQIIQQ",
            name,
            typ,
            flags,
            addr,
            offset,
            size,
            link,
            info,
            align,
            entsz,
        )

    # name offsets in shstr: 1=.text 7=.shstrtab 17=.symtab 25=.strtab
    shdrs = b"".join(
        [
            bytes(64),
            shdr(1, 1, 6, 0, off_text, len(text), 0, 0, 1, 0),  # PROGBITS AX
            shdr(7, 3, 0, 0, off_shstr, len(shstr), 0, 0, 1, 0),  # STRTAB
            shdr(17, 2, 0, 0, off_sym, 48, 4, 1, 8, 24),  # SYMTAB
            shdr(25, 3, 0, 0, off_str, len(strtab), 0, 0, 1, 0),
        ]
    )
    # null + add (GLOBAL FUNC, shndx=1, value=0, size=len(text))
    symtab = bytes(24) + struct.pack(
        "<IBBHQQ",
        1,
        (1 << 4) | 2,
        0,
        1,
        0,
        len(text),
    )
    ehdr = struct.pack(
        "<16sHHIQQQIHHHHHH",
        b"\x7fELF" + bytes([2, 1, 1, 0]) + bytes(8),
        1,  # ET_REL
        62,
        1,
        0,
        0,
        off_sh,
        0,
        ehdr_sz,
        0,
        0,
        64,
        5,
        2,
    )
    return b"".join(
        [ehdr, text, shstr, pad_shstr, symtab, strtab, pad_str, shdrs]
    )


def header_bytes(blob: bytes) -> str:
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        "/* Generated by tools/make_rtadd_elf.py. Do not edit. */\n"
        "#pragma once\n"
        "static const unsigned char rtadd_elf[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned rtadd_elf_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    blob = build()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(blob)
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
