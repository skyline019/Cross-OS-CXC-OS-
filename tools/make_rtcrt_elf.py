#!/usr/bin/env python3
"""ET_REL CRT: ans() calls UND twice via PC32 (cross-#lib). M109."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

# ans: mov rdi, 21; call twice; ret
ANS = bytes.fromhex("48C7C715000000E800000000C3")
# PC32 field sits after the E8 opcode (mov rdi,imm32 is 7 bytes).
CALL_FIELD = 8

R_X86_64_PC32 = 2
SHT_PROGBITS = 1
SHT_SYMTAB = 2
SHT_STRTAB = 3
SHT_RELA = 4
SHN_UNDEF = 0


def build() -> bytes:
    text = ANS
    # strtab: \0 ans \0 twice \0
    strtab = b"\x00ans\x00twice\x00"
    shstr = b"\x00.text\x00.rela.text\x00.shstrtab\x00.symtab\x00.strtab\x00"

    ehdr_sz = 64
    off_text = ehdr_sz
    # syms: null, ans (DEFINED), twice (UND)
    nsym = 3
    rela = struct.pack(
        "<QQq",
        CALL_FIELD,
        (2 << 32) | R_X86_64_PC32,  # sym index 2 = twice UND
        -4,
    )
    off_rela = off_text + len(text)
    off_shstr = off_rela + len(rela)
    off_sym = (off_shstr + len(shstr) + 7) & ~7
    pad_shstr = b"\x00" * (off_sym - (off_shstr + len(shstr)))
    off_str = off_sym + nsym * 24
    off_sh = (off_str + len(strtab) + 7) & ~7
    pad_str = b"\x00" * (off_sh - (off_str + len(strtab)))

    def shdr(name, typ, flags, addr, offset, size, link, info, align, entsz):
        return struct.pack(
            "<IIQQQQIIQQ",
            name,
            typ,
            flags,
            addr,
            offset,
            size,
            link,
            info,
            align,
            entsz,
        )

    # 0 null, 1 .text, 2 .rela.text, 3 .shstrtab, 4 .symtab, 5 .strtab
    # shstr: 1=.text 7=.rela.text 18=.shstrtab 28=.symtab 36=.strtab
    shdrs = b"".join(
        [
            bytes(64),
            shdr(1, SHT_PROGBITS, 6, 0, off_text, len(text), 0, 0, 1, 0),
            shdr(7, SHT_RELA, 0, 0, off_rela, len(rela), 4, 1, 8, 24),
            shdr(18, SHT_STRTAB, 0, 0, off_shstr, len(shstr), 0, 0, 1, 0),
            shdr(28, SHT_SYMTAB, 0, 0, off_sym, nsym * 24, 5, 1, 8, 24),
            shdr(36, SHT_STRTAB, 0, 0, off_str, len(strtab), 0, 0, 1, 0),
        ]
    )

    # null + ans GLOBAL FUNC shndx=1 + twice GLOBAL FUNC UND
    symtab = (
        bytes(24)
        + struct.pack("<IBBHQQ", 1, (1 << 4) | 2, 0, 1, 0, len(text))
        + struct.pack("<IBBHQQ", 5, (1 << 4) | 2, 0, SHN_UNDEF, 0, 0)
    )

    ehdr = struct.pack(
        "<16sHHIQQQIHHHHHH",
        b"\x7fELF" + bytes([2, 1, 1, 0]) + bytes(8),
        1,
        62,
        1,
        0,
        0,
        off_sh,
        0,
        ehdr_sz,
        0,
        0,
        64,
        6,
        3,
    )
    return b"".join(
        [ehdr, text, rela, shstr, pad_shstr, symtab, strtab, pad_str, shdrs]
    )


def header_bytes(blob: bytes) -> str:
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        "/* Generated by tools/make_rtcrt_elf.py. Do not edit. */\n"
        "#pragma once\n"
        "static const unsigned char rtcrt_elf[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned rtcrt_elf_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    blob = build()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(blob)
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
