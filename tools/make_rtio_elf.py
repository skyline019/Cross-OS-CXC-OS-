#!/usr/bin/env python3
"""ET_REL IO/string: cwrite/strlen/memcpy/memset/memcmp (SysV). M111/M112."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

# cwrite(rdi=buf, rsi=len)
CWRITE = bytes.fromhex("4889F24889FEBF01000000B801000000CD80C3")

# strlen(rdi=s)
STRLEN = bytes.fromhex("31C0803C0700740548FFC0EBF5C3")

# memcpy(rdi=dst, rsi=src, rdx=n)
MEMCPY = bytes.fromhex(
    "4889F84885D2740F8A0E880F48FFC648FFC748FFCA75F1C3"
)

# memset(rdi=dst, rsi=c, rdx=n): mov rax,rdi; test rdx,rdx; je done;
# mov cl,sil; L: mov [rdi],cl; inc rdi; dec rdx; jnz L; ret
MEMSET = bytes.fromhex("4889F84885D2740D408ACE880F48FFC748FFCA75F6C3")

# memcmp(rdi=a, rsi=b, rdx=n): 0 if equal else 1
# xor eax,eax; test rdx,rdx; je done;
# L: mov cl,[rdi]; cmp cl,[rsi]; jne diff;
# inc rdi; inc rsi; dec rdx; jnz L; ret;
# diff: mov eax,1; ret
MEMCMP = bytes.fromhex(
    "31C04885D274118A0F3A0E750C48FFC748FFC648FFCA75EFC3B801000000C3"
)

FUNCS = (
    ("cwrite", CWRITE),
    ("strlen", STRLEN),
    ("memcpy", MEMCPY),
    ("memset", MEMSET),
    ("memcmp", MEMCMP),
)

SHT_PROGBITS = 1
SHT_SYMTAB = 2
SHT_STRTAB = 3


def build() -> bytes:
    text = b"".join(body for _, body in FUNCS)
    offsets: list[tuple[str, int, int]] = []
    at = 0
    for name, body in FUNCS:
        offsets.append((name, at, len(body)))
        at += len(body)

    strtab = b"\x00" + b"".join(n.encode("ascii") + b"\x00" for n, _, _ in offsets)
    shstr = b"\x00.text\x00.shstrtab\x00.symtab\x00.strtab\x00"

    ehdr_sz = 64
    off_text = ehdr_sz
    nsym = 1 + len(offsets)
    off_shstr = off_text + len(text)
    off_sym = (off_shstr + len(shstr) + 7) & ~7
    pad_shstr = b"\x00" * (off_sym - (off_shstr + len(shstr)))
    off_str = off_sym + nsym * 24
    off_sh = (off_str + len(strtab) + 7) & ~7
    pad_str = b"\x00" * (off_sh - (off_str + len(strtab)))

    def shdr(name, typ, flags, addr, offset, size, link, info, align, entsz):
        return struct.pack(
            "<IIQQQQIIQQ",
            name,
            typ,
            flags,
            addr,
            offset,
            size,
            link,
            info,
            align,
            entsz,
        )

    shdrs = b"".join(
        [
            bytes(64),
            shdr(1, SHT_PROGBITS, 6, 0, off_text, len(text), 0, 0, 1, 0),
            shdr(7, SHT_STRTAB, 0, 0, off_shstr, len(shstr), 0, 0, 1, 0),
            shdr(17, SHT_SYMTAB, 0, 0, off_sym, nsym * 24, 4, 1, 8, 24),
            shdr(25, SHT_STRTAB, 0, 0, off_str, len(strtab), 0, 0, 1, 0),
        ]
    )

    symtab = bytearray(24)
    name_off = 1
    for name, value, size in offsets:
        symtab += struct.pack(
            "<IBBHQQ",
            name_off,
            (1 << 4) | 2,
            0,
            1,
            value,
            size,
        )
        name_off += len(name) + 1

    ehdr = struct.pack(
        "<16sHHIQQQIHHHHHH",
        b"\x7fELF" + bytes([2, 1, 1, 0]) + bytes(8),
        1,
        62,
        1,
        0,
        0,
        off_sh,
        0,
        ehdr_sz,
        0,
        0,
        64,
        5,
        2,
    )
    return b"".join(
        [ehdr, text, shstr, pad_shstr, bytes(symtab), strtab, pad_str, shdrs]
    )


def header_bytes(blob: bytes) -> str:
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        "/* Generated by tools/make_rtio_elf.py. Do not edit. */\n"
        "#pragma once\n"
        "static const unsigned char rtio_elf[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned rtio_elf_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    blob = build()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(blob)
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
