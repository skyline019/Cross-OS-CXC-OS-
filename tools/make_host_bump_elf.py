#!/usr/bin/env python3
"""Build/embed host-gcc -fPIC ET_REL for bump() — M118 GOTPCREL plant."""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "user" / "host_bump.c"


def compile_with_gcc(out: Path) -> None:
    gcc = shutil.which("gcc")
    if not gcc:
        raise RuntimeError("gcc not found")
    # -fPIC -fno-plt → R_X86_64_GOTPCREL for UND (M118); .rodata stays PC32.
    cmd = [
        gcc,
        "-c",
        "-m64",
        "-O0",
        "-fPIC",
        "-fno-plt",
        "-fno-asynchronous-unwind-tables",
        "-fno-ident",
        "-fno-stack-protector",
        "-o",
        str(out),
        str(SRC),
    ]
    subprocess.check_call(cmd)


def header_bytes(blob: bytes) -> str:
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        "/* Generated by tools/make_host_bump_elf.py from host gcc -c. */\n"
        "#pragma once\n"
        "static const unsigned char host_bump_elf[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned host_bump_elf_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    parser.add_argument(
        "--prebuilt",
        type=Path,
        help="If gcc missing, copy this ET_REL instead",
    )
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    try:
        compile_with_gcc(args.output)
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        if args.prebuilt and args.prebuilt.is_file():
            print(f"make_host_bump_elf: gcc failed ({exc}); using prebuilt", file=sys.stderr)
            args.output.write_bytes(args.prebuilt.read_bytes())
        else:
            raise
    blob = args.output.read_bytes()
    if blob[:4] != b"\x7fELF" or blob[16] != 1:
        raise SystemExit("output is not ELF64 ET_REL")
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
