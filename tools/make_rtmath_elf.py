#!/usr/bin/env python3
"""ET_REL: SysV add/mul/mac. Planted multi-symbol CRT subset for M107 #lib."""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

# add: mov rax,rdi; add rax,rsi; ret
ADD = bytes.fromhex("4889F84801F0C3")
# mul: mov rax,rdi; imul rax,rsi; ret
MUL = bytes.fromhex("4889F8480FAFC6C3")
# mac: mov rax,rdi; imul rax,rsi; add rax,rdx; ret
MAC = bytes.fromhex("4889F8480FAFC64801D0C3")

FUNCS = (
    ("add", ADD),
    ("mul", MUL),
    ("mac", MAC),
)


def build() -> bytes:
    text = b"".join(body for _, body in FUNCS)
    offsets: list[tuple[str, int, int]] = []
    at = 0
    for name, body in FUNCS:
        offsets.append((name, at, len(body)))
        at += len(body)

    shstr = b"\x00.text\x00.shstrtab\x00.symtab\x00.strtab\x00"
    strtab = b"\x00" + b"".join(name.encode("ascii") + b"\x00" for name, _, _ in offsets)

    ehdr_sz = 64
    off_text = ehdr_sz
    off_shstr = off_text + len(text)
    nsym = 1 + len(offsets)  # null + funcs
    off_sym = (off_shstr + len(shstr) + 7) & ~7
    pad_shstr = b"\x00" * (off_sym - (off_shstr + len(shstr)))
    off_str = off_sym + nsym * 24
    off_sh = (off_str + len(strtab) + 7) & ~7
    pad_str = b"\x00" * (off_sh - (off_str + len(strtab)))

    def shdr(name, typ, flags, addr, offset, size, link, info, align, entsz):
        return struct.pack(
            "<IIQQQQIIQQ",
            name,
            typ,
            flags,
            addr,
            offset,
            size,
            link,
            info,
            align,
            entsz,
        )

    # name offsets in shstr: 1=.text 7=.shstrtab 17=.symtab 25=.strtab
    shdrs = b"".join(
        [
            bytes(64),
            shdr(1, 1, 6, 0, off_text, len(text), 0, 0, 1, 0),
            shdr(7, 3, 0, 0, off_shstr, len(shstr), 0, 0, 1, 0),
            shdr(17, 2, 0, 0, off_sym, nsym * 24, 4, 1, 8, 24),
            shdr(25, 3, 0, 0, off_str, len(strtab), 0, 0, 1, 0),
        ]
    )

    symtab = bytearray(24)  # null
    name_off = 1
    for name, value, size in offsets:
        symtab += struct.pack(
            "<IBBHQQ",
            name_off,
            (1 << 4) | 2,  # GLOBAL FUNC
            0,
            1,
            value,
            size,
        )
        name_off += len(name) + 1

    ehdr = struct.pack(
        "<16sHHIQQQIHHHHHH",
        b"\x7fELF" + bytes([2, 1, 1, 0]) + bytes(8),
        1,  # ET_REL
        62,
        1,
        0,
        0,
        off_sh,
        0,
        ehdr_sz,
        0,
        0,
        64,
        5,
        2,
    )
    return b"".join(
        [ehdr, text, shstr, pad_shstr, bytes(symtab), strtab, pad_str, shdrs]
    )


def header_bytes(blob: bytes) -> str:
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        "/* Generated by tools/make_rtmath_elf.py. Do not edit. */\n"
        "#pragma once\n"
        "static const unsigned char rtmath_elf[] = {\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned rtmath_elf_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    blob = build()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(blob)
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
