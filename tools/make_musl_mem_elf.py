# Shallow plants may keep a fixed UND set (must already be on success rsp).
# Deep members: UND must be provided by other planted objs / hard_stubs.o.
ALLOWED_UND = {
    "ispunct": frozenset({"isalnum"}),
    "bzero": frozenset({"memset"}),
    "strnlen": frozenset({"memchr"}),
    "bcmp": frozenset({"memcmp"}),
    "strcspn": frozenset({"__stack_chk_fail", "__strchrnul", "memset"}),
    "strspn": frozenset({"__stack_chk_fail"}),
    "strpbrk": frozenset({"strcspn"}),
    "strrchr": frozenset({"__memrchr", "strlen"}),
    "memmove": frozenset({"__memcpy_fwd"}),
    "strdup": frozenset({"malloc", "memcpy", "strlen"}),
    "strtol": frozenset({"__intscan", "__shlim", "__stack_chk_fail"}),
    "intscan": frozenset({"___errno_location", "__shgetc", "__shlim"}),
    "shgetc": frozenset({"__uflow"}),
}


def extract_member(member: str, out: Path) -> None:
    ar = shutil.which("ar")
    if not ar:
        raise RuntimeError("ar not found")
    archive = next((p for p in CANDIDATE_ARCHIVES if p.is_file()), None)
    if archive is None:
        raise RuntimeError("musl libc.a not found")
    tmp = out.parent / f"_musl_{member}_extract"
    if tmp.exists():
        shutil.rmtree(tmp)
    tmp.mkdir(parents=True)
    try:
        subprocess.check_call([ar, "x", str(archive), MEMBERS[member]], cwd=tmp)
        src = tmp / MEMBERS[member]
        if not src.is_file():
            raise RuntimeError(f"{MEMBERS[member]} missing after ar x")
        out.write_bytes(src.read_bytes())
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def header_bytes(name: str, blob: bytes) -> str:
    arr = f"musl_{name}_elf"
    parts = [f"0x{b:02x}" for b in blob]
    lines = []
    for i in range(0, len(parts), 12):
        lines.append("    " + ", ".join(parts[i : i + 12]) + ",")
    return (
        f"/* Generated by tools/make_musl_mem_elf.py from musl {MEMBERS[name]}. */\n"
        "#pragma once\n"
        f"static const unsigned char {arr}[] = {{\n"
        + "\n".join(lines)
        + "\n};\n"
        f"static const unsigned {arr}_size = {len(blob)};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--member",
        choices=sorted(MEMBERS.keys()),
        required=True,
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    parser.add_argument("--prebuilt", type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    try:
        extract_member(args.member, args.output)
    except (RuntimeError, subprocess.CalledProcessError) as exc:
        if args.prebuilt and args.prebuilt.is_file():
            print(
                f"make_musl_mem_elf: extract failed ({exc}); using prebuilt",
                file=sys.stderr,
            )
            args.output.write_bytes(args.prebuilt.read_bytes())
        else:
            raise
    blob = args.output.read_bytes()
    if blob[:4] != b"\x7fELF" or blob[16] != 1:
        raise SystemExit("output is not ELF64 ET_REL")
    nm = shutil.which("nm")
    if nm:
        und = subprocess.check_output(
            [nm, "-u", str(args.output)], text=True, stderr=subprocess.DEVNULL
        )
        allowed = ALLOWED_UND.get(args.member, frozenset())
        found = set()
        for line in und.splitlines():
            sym = line.strip().split()[-1] if line.strip() else ""
            if sym:
                found.add(sym)
        extra = found - allowed
        if extra:
            raise SystemExit(
                f"{args.member}: nm -u unexpected: {sorted(extra)}\n{und}"
            )
        if found and not allowed:
            raise SystemExit(f"{args.member}: nm -u not empty:\n{und}")
    if args.header:
        args.header.parent.mkdir(parents=True, exist_ok=True)
        args.header.write_text(header_bytes(args.member, blob), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
